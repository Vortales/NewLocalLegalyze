_HEADER = (
    "Документ — ОБРАЩЕНИЕ В ОФИС ГЕНЕРАЛЬНОГО ПРОКУРОРА штата Сан-Андреас.\n"
    "Составь текст обращения строго по форме части 4 статьи 6 «Регламента "
    "подачи обращений в Офис Генерального прокурора штата San-Andreas».\n"
)


def build_request(values: dict, subject: str = "", notes: str = "") -> str:
    """Текст заявки в чат с ИИ: анкета + правила формы.

    Возвращает готовую строку для отправки. Пустые необязательные поля в
    заявку не попадают вовсе: пустой пункт формы — брак документа.
    """
    values = values or {}
    lines = [_HEADER]

    if subject:
        lines.append(f"Название темы на форуме: {subject}\n")

    lines.append("Данные от заявителя (это вход для тебя, в текст дословно не "
                 "переносится — перепиши официальным языком):")
    for field, (label, _src) in FIELDS.items():
        value = str(values.get(field, "") or "").strip()
        if not value:
            continue
        lines.append(f"- {label}: {value}")

    lines.append("")
    lines.append("Форма ответа (обязательные пункты, порядок не менять):")
    lines.append("От: гражданина штата Сан-Андреас <Имя Фамилия>")
    lines.append("В: Уважаемый Офис Генерального Прокурора штата Сан-Андреас")
    lines.append("1. Данные о заявителе: <Имя Фамилия; номер ID-карты>")
    lines.append("1.1 Данные о представителе заявителя: <только если представитель есть>")
    lines.append("2. Предмет обращения: <одна формулировка части 1 статьи 5 дословно>")
    lines.append("3. Сведения о нарушителе: <Имя Фамилия; идентификационный знак; организация>")
    lines.append("4. Дата и время события: <ДД.ММ.ГГГГ ЧЧ:ММ>")
    lines.append("5. Подробное описание ситуации: <связный текст, без списков и markdown>")
    lines.append("Настоящим заверяю, что все показания, пояснения и документация "
                 "являются подлинными.")
    lines.append("К заявлению прилагаю:")
    lines.append("6. Ксерокопия идентификационной карты или других документов, "
                 "удостоверяющих личность заявителя: <ссылка>")
    lines.append("7. Электронную почту и номер телефона: <почта>, <телефон>")
    lines.append("8. Доказательства правонарушения: <ссылки и тайм-коды>")
    lines.append("9. Копия договора о представлении интересов: <только при представителе>")
    lines.append("10. Документ, подтверждающий полномочия представителя: "
                 "<только при представителе>")
    lines.append("Дата подачи заявления: <ДД.ММ.ГГГГ>")
    lines.append("Подпись и расшифровка заявителя: <И. Фамилия>")
    lines.append("")
    lines.append("Правила:")
    lines.append("- пункты 1.1, 9 и 10 печатай ТОЛЬКО если представитель указан; иначе "
                 "строк этих пунктов в ответе быть не должно;")
    lines.append("- предмет обращения — дословная формулировка из части 1 статьи 5, "
                 "не свободная фраза;")
    lines.append("- если видеоматериал длиннее двух минут, в пункте 8 обязательны "
                 "тайм-коды каждого значимого эпизода (ч. 3 ст. 9);")
    lines.append("- в описании ситуации запрещены markdown, эмодзи и таблицы; "
                 "только обычный текст;")
    lines.append("- не выдумывай реквизиты: чего нет в данных — оставь пустым и "
                 "напиши об этом отдельной строкой после обращения;")
    lines.append("")
    lines.append("Ответ выдай ровно в таком виде:")
    lines.append(APPEAL_START)
    lines.append("<готовый текст обращения в BB-коде: [B], [I], [U], [CENTER], "
                 "[LIST], [URL], [SPOILER]>")
    lines.append(APPEAL_END)
    lines.append("После маркера — одна строка «Чего не хватает:» с перечнем "
                 "недостающих реквизитов (или «нет»).")
    if notes:
        lines.append("")
        lines.append(f"Дополнительно от оператора: {notes}")
    return "\n".join(lines)


