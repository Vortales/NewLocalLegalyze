def extract_appeal(text: str) -> str:
    """Готовое обращение из ответа ИИ (между маркерами). Пусто — маркеров нет."""
    raw = str(text or "")
    start = raw.find(APPEAL_START)
    if start < 0:
        return ""
    body = raw[start + len(APPEAL_START):]
    end = body.find(APPEAL_END)
    if end >= 0:
        body = body[:end]
    return body.strip("\n")


def extract_notes(text: str) -> str:
    """Строка «Чего не хватает: …» из ответа ИИ (пусто — её нет)."""
    match = re.search(r"Чего\s+не\s+хватает\s*:\s*(.+)", str(text or ""), re.I)
    return match.group(1).strip() if match else ""


def check_form(appeal: str) -> list:
    """Чего не хватает в готовом обращении: [(ключ, что искать)].

    Проверяются только обязательные пункты формы: остальное — дело ИИ.
    """
    text = str(appeal or "")
    low = text.lower()
    missing = []
    for key, marks in REQUIRED_MARKS.items():
        if not any(mark.lower() in low for mark in marks):
            missing.append((key, marks[0]))
    return missing


def docx_name(values: dict, date: str = "") -> str:
    """Имя файла обращения: «Обращение в ОГП — Max Ferstapaninov 15.11.2026.txt»."""
    name = str((values or {}).get("applicant", "") or "").strip() or "Заявитель"
    safe = re.sub(r"[^\w\s.\-—]", "", name).strip().replace(" ", " ")
    tail = f" {date}" if date else ""
    return f"Обращение в ОГП — {safe}{tail}.txt"
