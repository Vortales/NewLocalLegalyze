"""ogp_appeal.py — «Документы → Обращение в ОГП» (v60).

Задача пользователя: «можешь еще сделать в Документы „Обращение в ОГП“, где я
описываю ситуацию и ситуацию в доказательствах, прилагаю необходимые ссылки и
т.д., отправляется всё ИИ и получаю в виде BB-кода готовое обращение».

Как устроено:

1. оператор заполняет анкету: заявитель, ИД, контакты, категория обращения
   (ст. 5 Регламента), нарушитель, дата и время, описание ситуации,
   доказательства со ссылками и тайм-кодами;
2. постоянные реквизиты (телефон, почта, Discord, адрес) подставляются из
   «Шаблон» — окно `main.TemplateWindow`;
3. в чат уходит ЗАЯВКА: анкета + правила формы (ст. 6 ч. 4 Регламента подачи
   обращений в Офис Генерального прокурора) + требование отдать готовый текст
   в BB-коде между маркерами `===ОБРАЩЕНИЕ BB===` и `===КОНЕЦ ОБРАЩЕНИЯ===`;
4. из ответа ИИ текст с маркерами забирается как есть и копируется в буфер —
   остаётся вставить на форум.

Правило пользователя, которое держит этот модуль: «всё, что написано мной,
не должно попасть в документы, а сперва отправляется ИИ и уже ответ ИИ после
парсинга вставляется». Поэтому здесь нет «сборки текста из полей»: текст
обращения всегда пишет ИИ, а локальный код только проверяет, что в ответе есть
все обязательные пункты формы.
"""

from __future__ import annotations

import re

#: Маркеры ответа ИИ с готовым обращением.
APPEAL_START = "===ОБРАЩЕНИЕ BB==="
APPEAL_END = "===КОНЕЦ ОБРАЩЕНИЯ==="

#: Категории обращения — дословно часть 1 статьи 5 Регламента подачи
#: обращений (заявитель обязан указать одну из формулировок).
CATEGORIES: tuple = (
    "заявление о преступлении, совершённом гражданским лицом",
    "заявление о нарушении законодательства (не содержащем признаков преступления), "
    "совершённом гражданским лицом",
    "заявление о преступлении, совершённом должностным лицом при исполнении либо "
    "в связи с исполнением служебных обязанностей",
    "заявление о нарушении законодательства (не содержащем признаков преступления), "
    "совершённом должностным лицом при исполнении либо в связи с исполнением "
    "служебных обязанностей",
    "заявление о преступлении, совершённом должностным лицом вне исполнения "
    "служебных обязанностей",
    "заявление о нарушении законодательства (не содержащем признаков преступления), "
    "совершённом должностным лицом вне исполнения служебных обязанностей",
    "заявление об обжаловании решения (или иного акта) должностного лица",
)

#: Поля анкеты: ключ → (подпись, что подставляется из «Шаблон» или "").
FIELDS: dict = {
    "applicant": ("Заявитель (Имя Фамилия)", "Name"),
    "applicant_id": ("Номер ID-карты", "ID"),
    "phone": ("Телефон", "Phone"),
    "email": ("Электронная почта", "Email"),
    "discord": ("Discord (необязательно)", "Discord"),
    "representative": ("Представитель (Имя Фамилия, ID; необязательно)", ""),
    "category": ("Предмет обращения (ст. 5 Регламента)", ""),
    "offender": ("Нарушитель: Имя Фамилия", ""),
    "offender_id": ("Идентификационный знак (ОПЗ) нарушителя", ""),
    "offender_org": ("Организация нарушителя", ""),
    "date_time": ("Дата и время события (ДД.ММ.ГГГГ ЧЧ:ММ)", ""),
    "place": ("Место события", ""),
    "situation": ("Подробное описание ситуации", ""),
    "evidence": ("Доказательства: ссылки и тайм-коды", ""),
    "id_copy": ("Ссылка на копию ID-карты", ""),
    "contract": ("Ссылка на договор о представлении интересов (если есть)", ""),
    "authority": ("Ссылка на документ о полномочиях представителя (если есть)", ""),
    "demands": ("Что просите (необязательно — иначе ИИ выведет из ситуации)", ""),
}

#: Обязательные пункты формы (ч. 4 ст. 6) — по ним проверяется ответ ИИ.
REQUIRED_MARKS: dict = {
    "заявитель": ("От:",),
    "адресат": ("В:",),
    "предмет": ("Предмет обращения",),
    "нарушитель": ("Сведения о нарушителе",),
    "дата": ("Дата и время события",),
    "описание": ("Подробное описание ситуации",),
    "id": ("Ксерокопия идентификационной карты",),
    "contacts": ("Электронную почту и номер телефона",),
    "evidence": ("Доказательства правонарушения",),
    "signature": ("Подпись и расшифровка",),
}

#: Тема форума по ч. 2 и ч. 3 статьи 6 Регламента.
SUBJECT_CITIZEN = "Обращение в ОГП от гр-а {name}"
SUBJECT_OFFICER = "Обращение в Генеральную прокуратуру от гр-а {name}"


def subject_for(name: str, against_officer: bool = False) -> str:
    """Название темы обращения (ч. 2 или ч. 3 ст. 6 Регламента)."""
    name = str(name or "").strip() or "[Имя Фамилия]"
    return (SUBJECT_OFFICER if against_officer else SUBJECT_CITIZEN).format(name=name)


def template_value(template: dict, field: str) -> str:
    """Постоянный реквизит из «Шаблон» (пусто — в шаблоне не заполнено)."""
    key = FIELDS.get(field, ("", ""))[1]
    if not key:
        return ""
    return str((template or {}).get(key, "") or "").strip()


def prefill(template: dict) -> dict:
    """Значения анкеты, которые можно взять из «Шаблон»."""
    result = {}
    for field in FIELDS:
        value = template_value(template, field)
        if value:
            result[field] = value
    return result


def missing_fields(values: dict) -> list:
    """Обязательные поля, которые пусты: [(ключ, подпись)].

    Замечание пользователя: «если в Шаблон не заполнено — то уже требовать
    вручную». Поэтому проверка одна и та же и для «Шаблон», и для анкеты.
    """
    required = ("applicant", "applicant_id", "phone", "email", "category",
                "offender_org", "date_time", "situation", "evidence")
    result = []
    for field in required:
        if not str((values or {}).get(field, "") or "").strip():
            result.append((field, FIELDS[field][0]))
    return result


def missing_contact_fields(values: dict) -> list:
    """Отдельно: телефон и почта — их пользователь просил тянуть из «Шаблон»."""
    result = []
    for field in ("phone", "email"):
        if not str((values or {}).get(field, "") or "").strip():
            result.append((field, FIELDS[field][0]))
    return result


