"""ai_request.py — «в поле запроса минимум текста, все данные — в файлах» (v50).

Замечание пользователя:

    «ранее ты напрямую вставлял текст в окно запроса ИИ при нажатии
    „Проверка ИИ“ и „Сформировать“, теперь текст обращения экспортируй в файл
    „Обращение.txt“ и экспортируй его в ИИ, теперь минимум чистого текста ИИ
    в поле запроса, больше файлов, в которых вся эта информация».

Что было. В поле ввода уходила ВСЯ заявка одним куском: у «Проверки ИИ» —
«ЗАЯВКА НА ПРОВЕРКУ ОБРАЩЕНИЯ …» и ниже текст обращения целиком, у
«Сформировать» — «ЗАЯВКА НА ПОСТАНОВЛЕНИЕ ПРОКУРОРА …» с обращением и
обстоятельствами. Файл-вложение при этом был один, а вся содержательная часть
дублировалась в сообщении.

Что стало (правило этого модуля):

    обращение живёт ОТДЕЛЬНЫМ файлом «Обращение.txt» и прикладывается к чату;
    заявка (реквизиты этапа, что проверить, формат ответа) — тоже файлом;
    в поле запроса остаётся короткая служебная фраза: какой файл читать и
    что вернуть.

Модуль не зависит от Qt и браузера: всё проверяется тестами.
"""

from __future__ import annotations

from pathlib import Path

#: Как называется файл с текстом обращения в папке дела/этапа.
APPEAL_FILE_NAME = "Обращение.txt"

#: Заголовок, который ставится в начало экспортированного обращения. Он
#: нужен, чтобы файл читался как документ, а не как обрывок текста.
APPEAL_FILE_TITLE = "ОБРАЩЕНИЕ ГРАЖДАНИНА (форма Офиса Генерального прокурора)"


def appeal_file_text(appeal: str) -> str:
    """Содержимое «Обращение.txt»: заголовок + текст обращения как есть."""
    body = str(appeal or "").replace("\r\n", "\n").strip()
    return f"{APPEAL_FILE_TITLE}\n\n{body}\n"


def write_appeal_file(folder, appeal: str) -> Path:
    """Кладёт текст обращения в `<папка>/Обращение.txt` и возвращает путь."""
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / APPEAL_FILE_NAME
    path.write_text(appeal_file_text(appeal), encoding="utf-8")
    return path


def intake_message(appeal_name: str = APPEAL_FILE_NAME) -> str:
    """Короткое сообщение к «Проверке ИИ» (вместо простыни текста)."""
    return (
        f"Проверь обращение. Текст обращения — во вложении «{appeal_name}», "
        "порядок проверки и формат ответа — в файле заявки. Не пересказывай "
        "вложения и не описывай их; ответь только служебным блоком проверки "
        "обращения по формату промта."
    )


def document_message(request_name: str, appeal_name: str = APPEAL_FILE_NAME) -> str:
    """Короткое сообщение к «Сформировать» (вместо простыни текста)."""
    return (
        f"Сформируй постановление Прокурора. Исходные данные — во вложениях: "
        f"«{request_name}» (заявка: этап, вид решения, обстоятельства) и "
        f"«{appeal_name}» (текст обращения гражданина). Работай только с этими "
        "файлами, не описывай вложения и не разбирай шапку и подписи; ответь "
        "одним блоком постановления по формату промта."
    )
