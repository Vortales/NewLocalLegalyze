def step_index(step_number: int) -> str:
    """Метка шага этапа 2 для папки и имени файла: 1 → «2.1»."""
    return f"2.{int(step_number)}"


def etap_folder(etap: str, step_number: int = 0) -> str:
    """Имя подпапки этапа: «эт.1», «эт.2.1», «эт.3»."""
    if etap == ETAP_1:
        return "эт.1"
    if etap == ETAP_2:
        return f"эт.{step_index(step_number)}"
    if etap == ETAP_3:
        return "эт.3"
    return etap


def etap_from_folder(folder: str) -> tuple:
    """Обратный разбор: «эт.2.3» → ('work', 3)."""
    match = re.search(r"эт\.\s*(\d)(?:\.(\d+))?", str(folder or ""))
    if not match:
        return ("", 0)
    first = int(match.group(1))
    second = int(match.group(2) or 0)
    if first == 1:
        return (ETAP_1, 0)
    if first == 2:
        return (ETAP_2, second)
    if first == 3:
        return (ETAP_3, 0)
    return ("", 0)
