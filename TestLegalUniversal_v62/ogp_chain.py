PLAN_START = "===ПЛАН ЭТАПА 2==="
PLAN_END = "===КОНЕЦ ПЛАНА==="

#: Строка шага плана: «1. О возбуждении уголовного дела — зачем нужно».
_STEP_LINE = re.compile(
    r"^\s*(?:шаг\s*)?(\d{1,2})\s*(?:[.)]|[-—–])\s*(.+)$", re.I)


def plan_lines(text: str) -> list:
    """Текст между маркерами плана (пусто — маркеров нет)."""
    raw = str(text or "")
    start = raw.find(PLAN_START)
    if start < 0:
        return []
    body = raw[start + len(PLAN_START):]
    end = body.find(PLAN_END)
    if end >= 0:
        body = body[:end]
    return [line.strip() for line in body.splitlines() if line.strip()]


def parse_plan(text: str) -> list:
    """План этапа 2: [{'n': 1, 'kind': 'case', 'title': ..., 'why': ...}].

    Разбор терпим к вёрстке: «1.», «1)», «Шаг 1 —», точка с запятой, тире и
    двоеточие как разделитель пояснения. Незнакомый вид шага сохраняется как
    есть (`kind` = ''), чтобы прокурор мог оставить свой вариант цепочки.
    """
    steps = []
    for line in plan_lines(text):
        match = _STEP_LINE.match(line)
        if not match:
            continue
        number, body = int(match.group(1)), match.group(2).strip()
        # «О возбуждении уголовного дела — нужно установить факт»
        title, why = body, ""
        for sep in (" — ", " – ", " - ", ": ", ";"):
            if sep in body:
                title, why = body.split(sep, 1)
                break
        title = title.strip(" .»«\"")
        kind = step_kind_from_text(title) or step_kind_from_text(why)
        steps.append({"n": number, "kind": kind, "title": title,
                      "why": why.strip(" .")})
    steps.sort(key=lambda item: item["n"])
    return steps


def plan_present(text: str) -> bool:
    return PLAN_START in str(text or "")


