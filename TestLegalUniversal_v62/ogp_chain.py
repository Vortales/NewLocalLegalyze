"""ogp_chain.py — цепочка этапов обращения в ОГП (v60).

Замечание пользователя (`Этапы Постановления.txt`, v60): обращение в Офис
Генерального прокурора проходит **три составляющие**:

* **этап 1** — судьба самого обращения. Пользователь ничего не уточняет: он
  вставляет обращение целиком, а ИИ решает. Блок-схема (и Регламент подачи
  обращений) дают не два, а пять исходов: принять к производству, отказать в
  рассмотрении, оставить без движения на 24 часа, переадресовать,
  прекратить производство;
* **этап 2** — работа по существу, и это **не один документ**: возбуждение
  уголовного дела, внесение изменений, приостановление трудового договора,
  истребование информации, вызов на допрос, наложение взыскания... ИИ сам
  моделирует цепочку под ситуацию и отдаёт её планом, а прокурор проходит
  шаги по очереди, внося результат каждого;
* **этап 3** — итог по выводам этапа 2: завершение производства, УДП или
  передача дела в суд. Если этап 1 отказал — этап 3 не наступает.

Модуль намеренно не зависит от Qt: разбор плана, нумерация шагов и выбор
следующего действия проверяются обычными тестами.

Соглашения по именам файлов: шаг этапа 2 — это `2.1`, `2.2`, `2.3` (папки
«AG-1 — эт.2.1 возбуждение УД»), этап 3 — `3`. Внутри одной папки обращения
PNG разных шагов не затирают друг друга.
"""

