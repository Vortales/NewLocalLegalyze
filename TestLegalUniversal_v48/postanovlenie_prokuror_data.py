def parse_appeal_text(raw: str) -> dict:
    """Разбирает текст обращения гражданина по пунктам формы ОГП (v37).

    Реальная ситуация: пользователь вставил в «Обстоятельства» ВСЁ обращение
    целиком — с «От:», «В:», нумерацией, почтой и подписью. В постановление
    этот текст уходил дословно, а в «УСТАНОВИЛ» появлялась строка
    «Место события: в ходе служебной деятельности». Теперь обращение
    разбирается на реквизиты, а обстоятельствами становится только описание
    ситуации (п. 5).
    """
    text = str(raw or "").replace("\r\n", "\n")
    result: dict = {}
    if not text.strip():
        return result

    buffer: dict = {}
    current = ""

    def flush(key: str) -> None:
        if not key:
            return
        value = " ".join(x.strip() for x in buffer.get(key, []) if x.strip())
        value = re.sub(r"\s{2,}", " ", value).strip(" ;,")
        if value and not result.get(key):
            result[key] = value

    for line in text.splitlines():
        clean = line.strip()
        if not clean:
            if current:
                buffer.setdefault(current, []).append("")
            continue
        # «От: Kirito Gold 178393» и «1.2 …» — не пункты формы обращения, а
        # нумерация списка; «От:» вообще не реквизит и разбор не открывает.
        if re.match(r"^(от|в|кому|куда)\s*:", clean, re.IGNORECASE):
            continue
        stripped = re.sub(r"^(?:\d{1,2}\.\d{1,2}|\d{1,2})[.)]?\s*", "", clean)
        low = stripped.lower()
        matched = ""
        for prefix, key in APPEAL_POINTS:
            if low.startswith(prefix):
                matched = key
                rest = stripped[len(prefix):].lstrip(" :—-")
                # v37: «Ксерокопия идентификационной карты ИЛИ ДРУГИХ
                # документов, удостоверяющих личность…» — продолжение названия
                # пункта, а не значение поля. В поле попадал только хвост
                # «или других документов…».
                if rest.lower().startswith(("или", "либо")):
                    rest = stripped
                flush(current)
                current = key
                buffer.setdefault(key, [])
                if rest:
                    buffer[key].append(rest)
                break
        if matched:
            continue
        if current:
            buffer.setdefault(current, []).append(clean)
    flush(current)

    # «5. Подробное описание ситуации:» мог быть пуст — тогда в поле попал
    # следующий реквизит. Такой «пересказ» описанием ситуации не считается.
    # Туда же попадал заголовок вида решения («О принятии обращения к
    # собственному производству») — в выгрузке v38 он замыкал пересказ.
    description = result.get("description", "")
    if description.lower().startswith(("подпись", "дата подачи", "доказательства",
                                      "ксерокопия", "электронную почту")):
        result.pop("description", None)
    else:
        # Хвост формы («Настоящим заверяю… К заявлению прилагаю:») — это не
        # описание события, а служебные строки обращения (выгрузка v37).
        description = re.split(r"Настоящим заверяю", description)[0].strip()
        description = re.split(r"К заявлению прилагаю", description)[0].strip()
        # v38: если «Подробное описание ситуации:» пуст, в него затягивался
        # следующий реквизит — «Дата подачи заявления: 07.11.2026». Это не
        # описание события.
        description = re.split(r"\bДата подачи заявления\s*:", description)[0].strip()
        description = re.split(r"\bПодпись и расшифровка\s*:", description)[0].strip()
        description = strip_doc_type_tail(description)
        if description:
            result["description"] = description
        else:
            result.pop("description", None)

    # v38: «Подпись и расшифровка заявителя: N. Hiddens» — в этой же строке
    # оказывался хвост из инструкции клиента («Подготовь постановление
    # Прокурора строго по этим данным…»). Подпись — одна строка, без хвоста.
    signature = result.get("signature", "")
    if signature:
        signature = re.split(r"Подготовь постановление", signature)[0]
        signature = re.split(r"\n", signature)[0].strip(" ;,")
        if signature:
            result["signature"] = signature
        else:
            result.pop("signature", None)
    # Предмет обращения: буква варианта «в)» остаётся в тексте — снимаем её.
    subject_text = result.get("appeal_subject", "")
    if subject_text:
        result["appeal_subject"] = re.sub(r"^[а-яa-z]\)\s*", "", subject_text,
                                          flags=re.IGNORECASE).strip()

    # «Kirito Gold 178393» -> ФИО + ID
    applicant = result.get("applicant_name", "")
    name, ident = split_subject(applicant, "")
    if name:
        result["applicant_name"] = name
    if ident:
        result["applicant_id"] = ident

    # «Todd Spencer 181956: FIB» -> ФИО, номер, организация
    violator = result.get("violator", "")
    if violator:
        # v38: реальная форма «Lui Killua ;Номер удостоверения: 44628 ;
        # Организация : FIB ; Должность и отдел: Head of Department , HRT».
        # Раньше «отдел» получал ВСЮ строку реквизитов, а номер удостоверения
        # не извлекался вовсе.
        chunks = [c.strip(" ;,") for c in re.split(r"[;\n]", violator) if c.strip(" ;,")]
        head = re.split(r"[:;,]", chunks[0], maxsplit=1)[0].strip()
        tail = violator[len(head):]
        vname, vid = split_subject(head, "")
        result["violator"] = vname or head
        if vid:
            result["violator_id"] = vid
        for chunk in chunks[1:]:
            low_chunk = chunk.lower()
            value = re.split(r"[:—]", chunk, maxsplit=1)[-1].strip(" ;,:—-")
            if "организац" in low_chunk or "ведомств" in low_chunk or "фракц" in low_chunk:
                if value:
                    result["violator_department"] = value
            elif "отдел" in low_chunk and value and not result.get("violator_division"):
                # «Должность и отдел: Head of Department , HRT» -> отдел HRT
                result["violator_division"] = value.split(",")[-1].strip()
            elif "удостоверен" in low_chunk or "опз" in low_chunk:
                digits = re.search(r"\d{3,10}", value)
                if digits:
                    result["violator_id"] = digits.group(0)

    return result


_APPEAL_FORM_MARKS = (
    "предмет обращения", "сведения о нарушителе", "данные о заявителе",
    "подробное описание ситуации", "дата подачи заявления",
    "подпись и расшифровка заявителя",
)


#: Строка-реквизит формы обращения: «5. Подробное описание ситуации: …».
_APPEAL_FORM_LINE = re.compile(
    r"^\s*(?:\d{1,2}[.)]?\s*)?(?:"
    + "|".join(re.escape(mark) for mark in _APPEAL_FORM_MARKS)
    + r")\s*:",
    re.IGNORECASE | re.MULTILINE,
)


def looks_like_appeal_form(text: str) -> bool:
    """Текст — бланк обращения гражданина в ОГП, а не описание ситуации.

    Считаем не упоминания слов, а строки-реквизиты: официальный пересказ
    («предмет обращения соответствует установленным категориям») бланком
    не считается, а «1. Данные о заявителе: …» — считается.
    """
    raw = str(text or "")
    if not raw.strip():
        return False
    if len(_APPEAL_FORM_LINE.findall(raw)) >= 2:
        return True
    low = raw.lower()
    return sum(1 for mark in _APPEAL_FORM_MARKS if f"{mark}:" in low) >= 3


#: Корни названий актов: по ним видно, о каком акте идёт речь, независимо
#: от падежа («Уголовный кодекс» / «Уголовного кодекса»).
_ACT_ROOTS: tuple[tuple[str, str], ...] = (
    ("уголовн", "ук"),
    ("процессуальн", "пк"),
    ("этическ", "этический кодекс"),
    ("административн", "ак"),
    ("устав", "устав"),
    ("конституц", "конституция"),
    ("регламент", "регламент"),
    ("закон", "закон об огп"),
)


def act_roots(text: str) -> set:
    """Корни актов, упомянутых в строке (для поиска повторов)."""
    low = str(text or "").lower()
    return {key for root, key in _ACT_ROOTS if root in low}


def acts_not_named(clause: str, act: str) -> str:
    """Часть названия акта, которая ещё НЕ названа в норме (v39).

    ИИ присылает «Нарушенный акт: Уголовный Кодекс штата Сан-Андреас,
    Процессуальный кодекс штата Сан-Андреас» и «Пункт нарушения: статья 16.4
    Уголовного кодекса штата Сан-Андреас, статья 17 Процессуального кодекса
    штата Сан-Андреас». Первое название уже есть в норме, и в тексте
    получалось «… статьи 17 Процессуального кодекса … Уголовного Кодекса …,
    Процессуальный кодекс …». Добавляем только те акты, которых в норме нет.
    """
    raw_act = _clean(act)
    if not raw_act:
        return ""
    clause_roots = act_roots(clause)
    if not clause_roots:
        return act_genitive(raw_act)
    parts = [part.strip() for part in re.split(r"[,;]", raw_act) if part.strip()]
    missing = [part for part in parts if not (act_roots(part) and act_roots(part) <= clause_roots)]
    if not missing:
        return ""
    return act_genitive(", ".join(missing))


#: «часть 1 статьи 16», «части 2 и 6 статьи 8» — ссылка на статью целиком.
_ARTICLE_REF = re.compile(r"част\w*\s+([\d.,\sи]+?)\s+стать\w+\s+(\d+(?:\.\d+)*)",
                          re.IGNORECASE)


def _same_story(first: str, second: str, threshold: float = 0.34) -> bool:
    """Два абзаца рассказывают одно и то же (v46).

    «При проведении предварительного изучения обращения … отсутствуют
    доказательства» и «В Офис Генерального прокурора поступило обращение …
    не прикреплены доказательства» — один и тот же вывод, переписанный дважды.
    """
    words_first = set(re.findall(r"[а-яёa-z]{4,}", str(first or "").lower()))
    words_second = set(re.findall(r"[а-яёa-z]{4,}", str(second or "").lower()))
    if not words_first or not words_second:
        return False
    return len(words_first & words_second) / len(words_first) >= threshold


def _dedupe_basis_segments(text: str) -> str:
    """Убирает из «Основания» повтор одной и той же нормы (v46).

    ИИ присылает сразу и «Пункт нарушения: пункт 14 части 1 статьи 16», и
    «Нормативное основание: часть 1 статьи 16 …». В бланке это выглядело как
    «Основание: пункт 14 части 1 статьи 16; …; часть 1 статьи 16 …; статьи
    27–28 …» — одна и та же статья дважды.
    """
    segments = [seg.strip(" .;,") for seg in str(text or "").split(";")]
    segments = [seg for seg in segments if seg]
    if len(segments) < 2:
        return "; ".join(segments)

    def arts(seg: str) -> set:
        return {f"{part.strip()} / {art}" for part, art in _ARTICLE_REF.findall(seg)}

    kept: list = []
    for seg in segments:
        low = seg.lower()
        if any(low == k.lower() for k in kept):
            continue
        seg_arts = arts(seg)
        redundant = False
        if seg_arts:
            for other in segments:
                if other is seg:
                    continue
                # ссылка без «пункта» про ту же статью уступает ссылке с пунктом
                if arts(other) == seg_arts and "пункт" in other.lower() \
                        and "пункт" not in low:
                    redundant = True
                    break
        if not redundant:
            kept.append(seg)
    return "; ".join(kept)


def _drop_repeated_acts(text: str) -> str:
    """Убирает повторные упоминания акта в «Основании» (выгрузка v38).

    «… статья 16.4 Уголовного кодекса …, статья 17 Процессуального кодекса …;
    Уголовный Кодекс штата Сан-Андреас, Процессуальный кодекс штата
    Сан-Андреас; часть 2 статьи 36 Конституции …» — перечисление актов после
    конкретных статей читается как ошибка: акт уже назван при норме.
    """
    raw = str(text or "")
    if not raw:
        return raw
    chunks = [chunk.strip() for chunk in raw.split(";") if chunk.strip()]
    named: set = set()
    kept: list = []
    for chunk in chunks:
        roots = act_roots(chunk)
        has_norm = bool(re.search(r"\b(стат|пункт|част|ст\.|ч\.|п\.)", chunk.lower())
                        or re.search(r"\d+\.\d+", chunk))
        if roots and not has_norm:
            # Часть состоит только из названий актов: печатаем лишь те, что
            # ещё не названы при конкретных нормах.
            unique, seen_here = [], set()
            for part in chunk.split(","):
                key = part.strip()
                if not key or key.lower() in seen_here:
                    continue
                seen_here.add(key.lower())
                part_roots = act_roots(key)
                if part_roots and part_roots <= named:
                    continue
                unique.append(key)
                named |= part_roots
            if unique:
                kept.append(", ".join(unique))
            continue
        named |= roots
        kept.append(chunk)
    return "; ".join(kept)


def _covered(fragment: str, text: str, threshold: float = 0.6) -> bool:
    """Похоже ли, что `fragment` уже упомянут в `text`.

    Нужно, чтобы «УСТАНОВИЛ» не повторял место события второй раз: в тексте
    может стоять «в здании EMS», а в поле — «здание EMS».
    """
    words = [w for w in re.findall(r"[\wА-Яа-яЁё-]{3,}", str(fragment or "").lower())]
    if not words:
        return False
    low = re.sub(r"[^\wА-Яа-яЁё]+", " ", str(text or "").lower())
    # сравниваем по началу слова: «здание» и «здании» — одно и то же место
    hits = sum(1 for w in words if w[:5] in low)
    return hits / len(words) >= threshold


def _normalize_gov_key(raw: str) -> str:
    key = _clean(raw).lower().replace("**", "").replace("__", "").replace("`", "")
    key = key.replace("«", "").replace("»", "").replace('"', "")
    key = re.sub(r"^[\s>*_`#>•·\d.)\]]+", "", key)
    key = key.replace("\u00a0", " ").rstrip(":").strip(" .")
    key = re.sub(r"\s+", " ", key)
    if key in GOV_ALIASES:
        return GOV_ALIASES[key]
    for field_key, _form, label in GOV_FIELDS:
        if key == label.lower():
            return field_key
    return ""


_SENT_SPLIT = re.compile(r"(?<=[.!?])\s+")


def _key(text: str) -> str:
    """Нормализованный ключ предложения для поиска дублей."""
    return re.sub(r"[^\wА-Яа-яЁё]+", " ", str(text or "").lower()).strip()


def sentences(text: str) -> list:
    """Делит текст на законченные предложения (для склейки без повторов)."""
    parts = [p.strip() for p in _SENT_SPLIT.split(str(text or "").strip()) if p.strip()]
    return parts


#: Строки интерфейса веб-чата, которые ИИ копирует в ответ (v37).
_CHAT_JUNK = re.compile(
    r"^(pdf|file|docx?|txt|png|jpe?g|image|изображение|вложение|"
    r"файл(ы)? приложен\w*|вы отправили \d+|ответ в режиме ии.*|"
    r"чат в режиме ии:?.*)$",
    re.IGNORECASE,
)


def is_chat_junk(line: str) -> bool:
    """Строка — элемент интерфейса чата, а не текст документа."""
    text = strip_markdown(str(line or "")).strip(" .:;«»\"'")
    if not text:
        return True
    if _CHAT_JUNK.match(text):
        return True
    # «Заявка (отправлено в чат).txt», «scan_1234.pdf»
    if re.search(r"\.(pdf|docx?|txt|png|jpe?g)$", text, re.IGNORECASE):
        return True
    return False


#: Эхо собственного документа: веб-клиент вернул отправленный текст вместе
#: с ответом, и шапка/вводная часть попадали в «Обстоятельства» (v37).
_GOV_ECHO = re.compile(
    r"^(state of san-andreas|office of the attorney general|"
    r"я,\s*прокурор|г\.\s*лос-сантос|постановление\s*№)",
    re.IGNORECASE,
)


def is_gov_echo(line: str) -> bool:
    """Строка — повтор шапки/вводной части документа, а не факт дела."""
    return bool(_GOV_ECHO.match(strip_markdown(str(line or "")).strip(" .:;")))


def _end_sentence(text: str) -> str:
    """Закрывает предложение точкой, если ИИ её не поставил (v41)."""
    body = str(text or "").strip()
    if not body:
        return ""
    if body[-1] in ".!?…:;":
        return body
    return body + "."


def append_unique(parts: list, text: str) -> None:
    """Добавляет предложения, которых ещё нет в `parts`.

    В выгрузке AG-2 «УСТАНОВИЛ» дважды повторял место события и один и тот же
    вывод: строки-поля ИИ склеивались с абзацем обстоятельств подряд.
    """
    known = _key(" ".join(parts))
    for sentence in sentences(scrub_chat_text(text)):
        body = sentence.strip(" ;,")
        if not body or is_chat_junk(body) or is_gov_echo(body):
            continue
        if is_placeholder(body) or _GOV_PLACEHOLDER.match(body):
            continue
        # «…образуют нарушение: по обстоятельствам, указанным в заявке» —
        # заглушка может быть и в середине предложения
        if re.search(r"(образуют нарушение|квалификац\w+)[:;]?\s*"
                     r"(по обстоятельствам|согласно обстоятельствам)", body, re.IGNORECASE):
            continue
        key = _key(body)
        if key and key in known:
            continue
        parts.append(body)
        known = (known + " " + key).strip()


