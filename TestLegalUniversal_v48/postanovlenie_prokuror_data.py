def is_placeholder(value: str) -> bool:
    """Значение — заглушка ИИ («по обстоятельствам, указанным в заявке»)."""
    text = _clean(value)
    if not text:
        return True
    text = text.strip(" .,;")
    if _GOV_EMPTY_ANSWERS.match(text):
        return True
    return bool(_GOV_PLACEHOLDER.match(text))


#: Значения «места события», которые местом дела не являются.
_NOT_A_PLACE_CITY = re.compile(
    r"^(?:г\.?\s*)?(?:лос[-\s]?сантос|los\s*santos)\s*\.?$", re.IGNORECASE)


def is_place_placeholder(value: str) -> bool:
    """«Место события: в ходе служебной деятельности» — заглушка, не адрес."""
    text = _clean(value)
    if not text or is_placeholder(text):
        return True
    # v38: ИИ подставлял в «Место события» город бланка («г. Лос-Сантос») —
    # это не место происшествия, печатать его в «УСТАНОВИЛ» нельзя.
    if _NOT_A_PLACE_CITY.match(text.strip()):
        return True
    return bool(_NOT_A_PLACE.search(text))


def strip_doc_type_tail(text: str) -> str:
    """Убирает из конца абзаца заголовок вида решения (выгрузка v38).

    Реальный случай AG-1: пересказ заявителя заканчивался строкой «О принятии
    обращения к собственному производству» — заголовок бланка попал в
    «УСТАНОВИЛ» как ещё одно предложение.
    """
    raw = str(text or "")
    lines = [line for line in raw.splitlines() if line.strip()]
    while lines and _clean(lines[-1]).lower().strip(" .") in {
            kind.lower() for kind in GOV_DOC_TYPES}:
        lines.pop()
    result = "\n".join(lines).strip()
    # Заголовок мог приклеиться к концу абзаца через точку/перенос:
    # «… ч. 2 ст. 1 гл. 15 УК. О принятии обращения к собственному производству»
    for kind in GOV_DOC_TYPES:
        pattern = r"[\s.,;:—–-]*" + re.escape(kind) + r"\s*[.,]?\s*$"
        result = re.sub(pattern, "", result, flags=re.IGNORECASE)
    return result.strip()


def strip_placeholder_clauses(text: str) -> str:
    """Выбрасывает из абзаца фразы-заглушки (v37).

    Реальная выгрузка AG-2: «УСТАНОВИЛ» начинался со строки «Место события:
    в ходе служебной деятельности на территории штата Сан-Андреас», хотя
    место события в деле не установлено. Такие фразы — не факт, а заполнитель.
    """
    raw = str(text or "")
    if not raw.strip():
        return ""
    cleaned: list = []
    for chunk in re.split(r"(?<=[.!?])\s+|\n+", raw):
        body = chunk.strip()
        if not body:
            continue
        if re.match(r"^место события\s*:", body, re.IGNORECASE) and is_place_placeholder(
                re.sub(r"^место события\s*:\s*", "", body, flags=re.IGNORECASE)):
            continue
        if is_chat_junk(body):
            continue
        cleaned.append(body)
    return " ".join(cleaned).strip()


#: Названия полей бланка, которые ИИ приклеивает к своему тексту (v41).
#: Выгрузка «Постановление_4»: «Обстоятельства» = «Видео длится 46 секунд …
#: сотрудник FIB 301 просто стоит спиной и никак не реагирует\nОтдел
